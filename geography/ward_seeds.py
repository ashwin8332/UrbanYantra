def nearest_ward_name(city_name: str, lon: float, lat: float, fallback: str = "Area") -> str:
    coords = WARD_COORDINATES.get(city_name, {})
    if not coords:
        return fallback
    best_name = fallback
    best_d = float("inf")
    for name, (clat, clon) in coords.items():
        d = (lon - clon) ** 2 + (lat - clat) ** 2
        if d < best_d:
            best_d = d
            best_name = name
    return best_name
